export function useGameTranslations() {
  const { language } = useLanguagePreferences()
  const gameText = computed(() => gameTranslations[language.value])

  return {
    gameText,
    language,
  }
}

export function getCurrentGameText(): GameTranslation {
  const { language } = useLanguagePreferences()

  return gameTranslations[language.value]
}

export type GameTranslation = (typeof gameTranslations)[Language]
